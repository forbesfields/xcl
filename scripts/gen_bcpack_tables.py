"""Generate crates/xcl/src/hle/bcpack/rans_tables.rs from Microsoft's silicon-rans sample
(MIT): the per-segment symbol frequencies of the 16 static models, for alphabets of 1 to 8
bits. The cumulative bases are not stored: base[k + 1] = base[k] + freq[k] * symbols(k), which
this script checks against the sample's own `base_table`, and so are not the reciprocal tables
(`rf`, `rs`, `rn`): the decoder divides, and this script checks that the sample's reciprocal
path gives the same symbol for every slot of every model.

usage: python scripts/gen_bcpack_tables.py <path to mdu_minirans.v>
(https://github.com/microsoft/silicon-rans/blob/main/mdu_minirans.v, commit 2f6827d)"""
import io, os, re, sys

src = io.open(sys.argv[1], encoding='utf-8').read()
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'crates', 'xcl', 'src', 'hle', 'bcpack', 'rans_tables.rs')
WIDTHS, MODELS, SEGS = 8, 16, 9  # the sample has a 9-bit alphabet and a 10th segment as well; no BCPack lane is that wide


def table(name):
    m = re.search(r'assign\s+' + name + r'\s*=\s*\'\{(.*?)\};\s*//\s*end\s+' + name, src, re.S)
    rows = [[int(v) for v in r.split(',')] for r in re.findall(r"'\{\s*([0-9,\s]+?)\s*\}", m.group(1))]
    assert len(rows) == 9 * 16 and all(len(r) == 10 for r in rows), name
    return [rows[w * 16:(w + 1) * 16] for w in range(9)]


base, freq, rf, rs, rn = (table(n + '_table') for n in ('base', 'freq', 'rf', 'rs', 'rn'))


def symbols(seg):
    return 1 if seg < 2 else 1 << (seg - 1)


for w in range(WIDTHS):
    for q in range(MODELS):
        b, f = base[w][q], freq[w][q]
        nseg = w + 2  # segment 0 is symbol 0, segment k >= 1 is symbols [2^(k-1), 2^k)
        acc = 0
        for k in range(nseg):
            assert b[k] == acc and f[k] >= 1, (w, q, k)
            acc += f[k] * symbols(k)
        assert acc == 65536 and not any(f[nseg:]), (w, q)
        # the sample's inverse (comparator chain, then a reciprocal multiply) is a division
        for cf in range(65536):
            seg = max((k for k in range(1, nseg) if cf >= b[k]), default=0)
            steps = ((((cf - b[seg] + rn[w][q][seg]) & 0xFFFF) * rf[w][q][seg]) >> 15) >> rs[w][q][seg]
            assert steps == (cf - b[seg]) // f[seg], (w, q, cf)

out = io.open(OUT, 'w', encoding='utf-8', newline='\n')
out.write('''// Generated by scripts/gen_bcpack_tables.py from Microsoft's silicon-rans sample (mdu_minirans.v,
// https://github.com/microsoft/silicon-rans commit 2f6827d): Copyright (c) Microsoft Corporation, MIT.
// `FREQ[bits - 1][q][segment]`: the frequency of each symbol of a segment, out of 65536. Segment 0
// is symbol 0, segment k >= 1 is the symbols 2^(k-1) .. 2^k - 1.

#![allow(clippy::unreadable_literal)]

''')
out.write(f'pub static FREQ: [[[u16; {SEGS}]; {MODELS}]; {WIDTHS}] = [\n')
for w in range(WIDTHS):
    out.write(f'    // {w + 1}-bit alphabet\n    [\n')
    for q in range(MODELS):
        out.write('        [' + ', '.join(str(v) for v in freq[w][q][:SEGS]) + '],\n')
    out.write('    ],\n')
out.write('];\n')
out.close()
print('wrote', os.path.normpath(OUT))
